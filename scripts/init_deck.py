#!/usr/bin/env python3
"""Copy the bundled GDUT templates to a new personal report directory."""
import argparse
from pathlib import Path
import re
import shutil
from xml.etree import ElementTree as ET
import zipfile

ROOT = Path(__file__).resolve().parents[1]
NS = {"a": "http://schemas.openxmlformats.org/drawingml/2006/main"}
TEX_ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$",
               "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}",
               "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def tex_escape(value):
    return "".join(TEX_ESCAPES.get(c, c) for c in value)


def fill_profile(path, fields):
    text = path.read_text(encoding="utf-8")
    for key, value in fields.items():
        if value is None:
            continue
        # The bundled profile uses a one-line, brace-delimited macro for each field.
        pattern = r"(\\(?:newcommand|renewcommand|providecommand)\{\\" + key + r"\}\{)[^\n]*?(\}\s*(?:%[^\n]*)?$)"
        text, count = re.subn(pattern, lambda m: m[1] + tex_escape(value) + m[2], text, count=1, flags=re.M)
        if count != 1:
            raise ValueError(f"Missing personal field in profile.tex: {key}")
    path.write_text(text, encoding="utf-8")


def replace_paragraph(paragraph, replacements):
    """Replace matches across DrawingML runs, retaining surrounding formatting."""
    nodes = paragraph.findall(".//a:t", NS)
    joined = "".join(n.text or "" for n in nodes)
    matches = []
    for old, new in replacements.items():
        if new is None:
            continue
        start = 0
        while (start := joined.find(old, start)) >= 0:
            matches.append((start, start + len(old), new))
            start += len(old)
    if not matches:
        return False
    # Work backwards so all original character offsets remain valid.
    for start, end, value in sorted(matches, reverse=True):
        pos = 0
        spans = []
        for node in nodes:
            length = len(node.text or "")
            spans.append((pos, pos + length, node))
            pos += length
        selected = [(a, b, n) for a, b, n in spans if a < end and b > start]
        if not selected:
            continue
        for i, (a, b, node) in enumerate(selected):
            raw = node.text or ""
            lo, hi = max(0, start - a), min(len(raw), end - a)
            node.text = raw[:lo] + (value if i == 0 else "") + raw[hi:]
    return True


def fill_pptx(path, replacements):
    # Parse to locate text runs, but replace only changed a:t payloads in the
    # original XML. Preserve namespace declarations and compatibility prefixes.
    from html import escape, unescape
    changed_parts = 0
    with zipfile.ZipFile(path) as src:
        parts = [(item, src.read(item.filename)) for item in src.infolist()]
    updated = []
    for item, data in parts:
        if item.filename.startswith("ppt/") and item.filename.endswith(".xml"):
            root = ET.fromstring(data)
            before = [n.text or "" for n in root.findall(".//a:t", NS)]
            for paragraph in root.findall(".//a:p", NS):
                replace_paragraph(paragraph, replacements)
            after = [n.text or "" for n in root.findall(".//a:t", NS)]
            if before != after:
                xml = data.decode("utf-8")
                matches = list(re.finditer(r"(<(?:[\w.-]+:)?t\b[^>]*>)(.*?)(</(?:[\w.-]+:)?t>)", xml, re.S))
                # Filter by namespace-insensitive text equality. DrawingML
                # assets generated by the bundled author use prefixed a:t.
                if len(matches) != len(before) or any(unescape(m[2]) != old for m, old in zip(matches, before)):
                    raise ValueError(f"Unsupported text serialization: {item.filename}")
                for match, old, new in reversed(list(zip(matches, before, after))):
                    if old != new:
                        xml = xml[:match.start(2)] + escape(new, quote=False) + xml[match.end(2):]
                data = xml.encode("utf-8")
                changed_parts += 1
        updated.append((item, data))
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as dst:
        for item, data in updated:
            dst.writestr(item, data)
    return changed_parts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--format", choices=["pptx", "beamer", "both"], default="pptx")
    parser.add_argument("--title")
    parser.add_argument("--name")
    parser.add_argument("--college")
    parser.add_argument("--supervisor")
    parser.add_argument("--date")
    args = parser.parse_args()
    target = args.output.resolve()
    if target.exists():
        parser.error(f"Target already exists; choose a new directory: {target}")
    asset_root = (ROOT / "assets").resolve()
    if target == asset_root or asset_root in target.parents:
        parser.error("Choose an output directory outside the bundled assets")
    for kind in (["beamer", "powerpoint"] if args.format == "both" else ["powerpoint" if args.format == "pptx" else "beamer"]):
        if not (ROOT / "assets" / kind).is_dir():
            parser.error(f"Missing bundled template: {kind}")
    target.mkdir(parents=True)
    if args.format in ("beamer", "both"):
        dest = target / "beamer"
        shutil.copytree(ROOT / "assets/beamer", dest,
                        ignore=shutil.ignore_patterns("build", "*.aux", "*.log", "__pycache__"))
        fill_profile(dest / "profile.tex", {"mytitle": args.title, "myauthor": args.name,
                     "mycollege": args.college, "myadvisor": args.supervisor, "mydate": args.date})
    if args.format in ("pptx", "both"):
        dest = target / "powerpoint"
        dest.mkdir()
        replacements = {"学术汇报模板": args.title, "汇报人姓名": args.name,
                        "学院 / 专业": args.college, "导师姓名": args.supervisor, "汇报日期": args.date}
        for filename in ("GDUT-Template.pptx", "GDUT-Template.potx"):
            original = ROOT / "assets/powerpoint" / filename
            if not original.is_file():
                raise FileNotFoundError(original)
            final = dest / filename
            shutil.copy2(original, final)
            fill_pptx(final, replacements)
    print(f"Created {args.format} report: {target}")


if __name__ == "__main__":
    main()
